const catalogs = { en, sv } as const satisfies Record<Locale, Record<MessageKey, string>>;

export function isLocale(value: string | null | undefined): value is Locale {
  return locales.includes(value as Locale);
}

export function translate(locale: Locale, key: MessageKey): string {
  return catalogs[locale][key];
}

export function formatDateTime(locale: Locale, value: Date | string, timeZone: string): string {
  return new Intl.DateTimeFormat(locale === "sv" ? "sv-SE" : "en-GB", {
    dateStyle: "long",
    timeStyle: "short",
    timeZone,
  }).format(typeof value === "string" ? new Date(value) : value);
}

export function formatCurrency(locale: Locale, minorUnits: number, currency: string): string {
  return new Intl.NumberFormat(locale === "sv" ? "sv-SE" : "en-GB", {
    currency,
    style: "currency",
  }).format(minorUnits / 100);
}
